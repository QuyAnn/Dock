    px,py=c1[0]+a*dx/d,c1[1]+a*dy/d
    p1=(px+h*dy/d,py-h*dx/d); p2=(px-h*dy/d,py+h*dx/d)
    return f"M{f(p1[0])} {f(p1[1])}A{f(r1)} {f(r1)} 0 1 0 {f(p2[0])} {f(p2[1])}A{f(r2)} {f(r2)} 0 0 1 {f(p1[0])} {f(p1[1])}Z"
